"""Ad hoc script -- NOT part of the doyra_ai package.

Turns models/results/phaseB_generalization_check.json (produced by
scripts/analyze_phaseB_phrases.py) into one plain-markdown draft
transcription per usul phrase, meant to be read and hand-corrected by a
person -- not a deliverable of the Phase A package.

Usage:
    python scripts/write_phaseB_drafts.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS_PATH = REPO_ROOT / "models" / "results" / "phaseB_generalization_check.json"
OUT_DIR = REPO_ROOT / "phaseB_drafts"


def main() -> None:
    with open(RESULTS_PATH, encoding="utf-8") as f:
        data = json.load(f)

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for name, hits in data["transcriptions"].items():
        lines = [
            f"# {name} -- draft transcription",
            "",
            "Auto-generated by the Phase A classifier + onset detector "
            "(`scripts/analyze_phaseB_phrases.py`). This is a starting point "
            "for hand-correction, not ground truth -- edit the `Label` "
            "column directly to fix mistakes.",
            "",
            f"- Hits detected: {len(hits)}",
            f"- Mean confidence: {data['per_file_mean_confidence'].get(name, 'n/a')}",
            "",
            "| Hit # | Time (s) | Label | Confidence |",
            "|---|---|---|---|",
        ]
        for i, hit in enumerate(hits, start=1):
            lines.append(f"| {i} | {hit['time_sec']:.3f} | {hit['pred']} | {hit['confidence']:.2f} |")
        lines.append("")

        out_path = OUT_DIR / f"{name}.md"
        out_path.write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {out_path} ({len(hits)} hits)")


if __name__ == "__main__":
    main()
